DEFAULT_TOPIC = "기타"


def classify(title: str, body: str = "") -> str:
    t = f"{title} {title} {body[:600]}".lower()  # 제목에 가중치
    best, score = DEFAULT_TOPIC, 0
    for name, kws in TOPICS:
        sc = sum(t.count(k) for k in kws)
        if sc > score:
            best, score = name, sc
    return best


